const CATALOG: Record<Locale, Dict> = { fr, en };

/** Resolve a key for a locale, falling back to French then the raw fallback/key.
 * Optional `params` replaces `{name}` placeholders in the resolved string. */
export function translate(locale: Locale, key: string, fallback?: string, params?: Record<string, string | number>): string {
  let out = CATALOG[locale]?.[key] ?? CATALOG.fr[key] ?? fallback ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) out = out.split(`{${k}}`).join(String(v));
  }
  return out;
}

/** Best-effort locale from the browser when the user hasn't chosen one. */
export function detectLocale(): Locale {
  if (typeof navigator === "undefined") return "fr";
  return navigator.language?.toLowerCase().startsWith("en") ? "en" : "fr";
}
