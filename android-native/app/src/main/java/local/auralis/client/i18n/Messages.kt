    private val catalog: Map<Locale, Map<String, String>> = mapOf(Locale.FR to fr, Locale.EN to en)

    /**
     * The locale used by non-composable call sites (models, view model). Updated
     * whenever the user switches language; defaults to French like the web.
     */
    @Volatile
    var current: Locale = Locale.FR

    /** Resolve a key for a locale, falling back to French then the raw fallback/key.
     *  Optional `params` replaces `{name}` placeholders in the resolved string. */
    fun translate(
        locale: Locale,
        key: String,
        fallback: String? = null,
        params: Map<String, Any> = emptyMap(),
    ): String {
        var out = catalog[locale]?.get(key) ?: fr[key] ?: fallback ?: key
        for ((k, v) in params) out = out.replace("{${k}}", v.toString())
        return out
    }

    /** [translate] against [current] — for non-composable call sites. */
    fun t(key: String, fallback: String? = null, params: Map<String, Any> = emptyMap()): String =
        translate(current, key, fallback, params)

    /** Every key defined for a locale (test hook for catalog completeness). */
    internal fun keys(locale: Locale): Set<String> = catalog[locale]?.keys ?: emptySet()

    // ---- locale-aware formatting --------------------------------------------

    /** "1 h 5 min" / "1 hr 5 min" — the web's formatLongDuration, localized. */
    fun formatLongDuration(totalSeconds: Double): String {
        if (!totalSeconds.isFinite()) return "—"
        val total = totalSeconds.toLong()
        val h = total / 3600
        val m = (total % 3600) / 60
        return if (h > 0) t("common.longDuration", params = mapOf("h" to h, "m" to m))
        else t("common.longDurationMin", params = mapOf("m" to m))
    }

    /** "2h 5m" compact recap duration (web InsightsView recap style). */
    fun formatCompactDuration(seconds: Long): String {
        val h = seconds / 3600
        val m = (seconds % 3600) / 60
        return if (h > 0) t("common.compactDuration", params = mapOf("h" to h, "m" to m))
        else t("common.compactDurationMin", params = mapOf("m" to m))
    }

    private val MONTH_KEYS = listOf(
        "month.jan", "month.feb", "month.mar", "month.apr", "month.may", "month.jun",
        "month.jul", "month.aug", "month.sep", "month.oct", "month.nov", "month.dec",
    )
    private val MONTH_SHORT_KEYS = MONTH_KEYS.map { it.replace("month.", "month.short.") }

    /** "Janvier 2026" from a "YYYY-MM" recap key. */
    fun monthLabel(key: String): String {
        val parts = key.split("-")
        val m = parts.getOrNull(1)?.toIntOrNull() ?: 1
        val name = t(MONTH_KEYS.getOrElse(m - 1) { key })
        return "$name ${parts.getOrNull(0) ?: ""}".trim()
    }

    /** "Janv. 26" chip label from a "YYYY-MM" recap key. */
    fun monthShortLabel(key: String): String {
        val parts = key.split("-")
        val m = parts.getOrNull(1)?.toIntOrNull() ?: 1
        val name = t(MONTH_SHORT_KEYS.getOrElse(m - 1) { key })
        return "$name ${parts.getOrNull(0)?.takeLast(2) ?: ""}"
    }
